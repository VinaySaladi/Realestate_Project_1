export const getPropertyBySlug = (slug) => properties.find((p) => p.slug === slug)

export const featuredProperties = properties.filter((p) => p.featured)

export const cities = [...new Set(properties.map((p) => p.location.city))].sort()

export function getSimilarProperties(property, limit = 3) {
  const score = (p) =>
    (p.location.city === property.location.city ? 2 : 0) + (p.type === property.type ? 1 : 0) + (p.status === property.status ? 1 : 0)
  return properties
    .filter((p) => p.id !== property.id)
    .sort((a, b) => score(b) - score(a))
    .slice(0, limit)
}
